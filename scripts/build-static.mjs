import { cpSync, mkdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const output = resolve(root, 'dist');
const publicFiles = ['index.html', 'style.css', 'tokens.css', 'base.css', 'story.js', 'app.js'];
rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });
for (const name of publicFiles) cpSync(resolve(root, name), resolve(output, name));
console.log('Built dist/ with the six explicit public application files.');
